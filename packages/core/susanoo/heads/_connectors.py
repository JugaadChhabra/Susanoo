"""Connector lookup for Agent Smith. [PRD › Connectors and API budget › Connector contract]

Jugaad owns `packages/core/susanoo/connectors/<name>.py`. Each connector module has:
  - `spec`: name, required fields, scopes, read vs write actions
  - `tools()`: the tool functions Agent Smith may wire into a generated agent
(`guide.md` and `test_connection()` are for the UI and are not used here.)

TODO(jugaad-connectors): the Protocols below are what Agent Smith was coded against. Once
`susanoo.connectors.<name>` exists, `load_connectors` already imports it by name; confirm the
`tools()` shape (see below) and delete the Protocols in favour of `susanoo.connectors.base`.

What Agent Smith assumes about `tools()`: a list of plain, self-contained Python functions. Their
source is copied into the generated repo's `agent/tools.py` (the generated repo cannot import
`susanoo`), so each function must import what it needs inside its body and read its credential
from an environment variable at call time. Credentials are injected by the sandbox as container env
vars [PRD › Credential handling]; a function that hard-codes one is refused.

Agent Smith never reads a connector's stored configuration or credentials, only `spec` and `tools()`.
"""

from __future__ import annotations

import ast
import builtins
import importlib
import inspect
import re
import textwrap
from collections.abc import Callable, Sequence
from dataclasses import dataclass
from typing import Any, Protocol

from susanoo.integrations import tracing

BEGIN_MARKER = "# --- BEGIN CONNECTOR TOOLS (generated by Agent Smith; edit via the tool layer only) ---"
END_MARKER = "# --- END CONNECTOR TOOLS ---"


class ConnectorError(Exception):
    """A selected connector is missing or its tools cannot be used. The message is plain English."""


class ConnectorSpec(Protocol):
    name: str
    required_fields: Sequence[str]
    scopes: Sequence[str]
    read_actions: Sequence[str]
    write_actions: Sequence[str]


class ConnectorModule(Protocol):
    """Structural type of `susanoo.connectors.<name>` (a module works as well as an object)."""

    spec: ConnectorSpec

    def tools(self) -> Sequence[Callable[..., Any]]: ...


@dataclass(frozen=True)
class ConnectorTool:
    connector: str
    name: str
    source: str  # dedented Python source of one function, no credentials


_CONNECTOR_NAME = re.compile(r"^[a-z][a-z0-9_]*$")
# An environment variable name such as GITHUB_TOKEN is how a tool is meant to find its credential.
_ENV_VAR_NAME = re.compile(r"^[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+$")


def load_connectors(names: Sequence[str]) -> list[ConnectorModule]:
    """Return the connector modules for `names`. This is the one place that knows where they live.

    TODO(jugaad-connectors): replace with `susanoo.connectors.<name>` once Jugaad's package exists
    (this already imports it dynamically, so no change is needed unless the module layout differs).
    """
    modules: list[ConnectorModule] = []
    for name in names:
        if not isinstance(name, str) or not _CONNECTOR_NAME.match(name):
            raise ConnectorError("A selected connection has an invalid name, so the agent was not given its tools.")
        try:
            modules.append(importlib.import_module(f"susanoo.connectors.{name}"))  # type: ignore[arg-type]
        except ModuleNotFoundError as exc:
            raise ConnectorError(
                f"The {name} connection is not available yet, so the agent cannot be given its tools."
            ) from exc
    return modules


def collect_tools(connectors: Sequence[ConnectorModule]) -> list[ConnectorTool]:
    """Turn each connector's `tools()` into source snippets.

    A tool is refused (plain-English error naming the connector and tool, never any value) unless it is
    safe to copy into the generated repo: no credential in its source, no closure, and no reference to
    anything defined outside the function body (the generated repo cannot import susanoo).
    """
    tools: list[ConnectorTool] = []
    seen: set[str] = set()
    for connector in connectors:
        cname = str(connector.spec.name)
        for fn in connector.tools():
            fname = getattr(fn, "__name__", "")
            if not fname.isidentifier() or fname == "<lambda>":
                raise ConnectorError(f"A tool from the {cname} connection has no usable name, so it was not added.")
            if fname in seen:
                raise ConnectorError(f"Two connection tools are both called {fname!r}, so none were added.")
            seen.add(fname)
            source = _tool_source(cname, fname, fn)
            tools.append(ConnectorTool(connector=cname, name=fname, source=source))
    return tools


def _tool_source(cname: str, fname: str, fn: Any) -> str:
    def refuse(reason: str) -> ConnectorError:
        return ConnectorError(f"The {fname!r} tool from the {cname} connection was not added: {reason}")

    if not inspect.isfunction(fn):
        raise refuse("it is not a plain function.")
    if fn.__code__.co_freevars:
        raise refuse("it uses values from outside itself (a closure), which would not exist in the generated app.")
    try:
        source = textwrap.dedent(inspect.getsource(fn)).rstrip() + "\n"
        tree = ast.parse(source)
    except (OSError, TypeError, SyntaxError) as exc:
        raise refuse("its source is not plain, self-contained code.") from exc
    if len(tree.body) != 1 or not isinstance(tree.body[0], (ast.FunctionDef, ast.AsyncFunctionDef)):
        raise refuse("its source is not a single function.")
    node = tree.body[0]

    if tracing.looks_secret_shaped(source):
        raise refuse("it appears to contain a secret. Tools must read credentials from the environment.")
    if _hardcoded_credential(node):
        raise refuse("it appears to contain a hard-coded credential. Tools must read credentials from the environment.")
    outside = _outside_names(node)
    if outside:
        raise refuse(
            "it relies on names defined outside the function "
            f"({', '.join(sorted(outside)[:5])}). Import modules inside the function body."
        )
    return source


def _fold(node: ast.AST) -> str | None:
    """The string a literal expression evaluates to (joined literals, f-strings of only literals), else None."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        left, right = _fold(node.left), _fold(node.right)
        return left + right if left is not None and right is not None else None
    if isinstance(node, ast.JoinedStr):
        parts = [_fold(v) for v in node.values]
        return None if any(p is None for p in parts) else "".join(p for p in parts if p is not None)
    return None


def _is_credential_literal(value: str | None) -> bool:
    return bool(value) and not _ENV_VAR_NAME.match(value or "")


def _target_name(node: ast.AST) -> str | None:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        return node.attr
    if isinstance(node, ast.Subscript):
        return _fold(node.slice)
    return None


def _hardcoded_credential(fn: ast.AST) -> bool:
    """True if a string literal is secret-shaped, or is bound to a credential-like name."""

    def sensitive_literal(name: str | None, value: ast.AST | None) -> bool:
        return (
            name is not None
            and value is not None
            and tracing.is_sensitive_name(name)
            and _is_credential_literal(_fold(value))
        )

    for node in ast.walk(fn):
        folded = _fold(node)
        if folded is not None and tracing.looks_secret_shaped(folded):
            return True
        if isinstance(node, ast.Assign):
            if any(sensitive_literal(_target_name(t), node.value) for t in node.targets):
                return True
        elif isinstance(node, (ast.AnnAssign, ast.AugAssign)):
            if sensitive_literal(_target_name(node.target), node.value):
                return True
        elif isinstance(node, ast.NamedExpr):
            if sensitive_literal(_target_name(node.target), node.value):
                return True
        elif isinstance(node, ast.keyword):
            if sensitive_literal(node.arg, node.value):
                return True
        elif isinstance(node, ast.Dict):
            for key, value in zip(node.keys, node.values, strict=True):
                if key is not None and sensitive_literal(_fold(key), value):
                    return True
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda)):
            a = node.args
            positional = [*a.posonlyargs, *a.args]
            pairs = list(zip(positional[len(positional) - len(a.defaults) :], a.defaults, strict=True))
            pairs += [(arg, d) for arg, d in zip(a.kwonlyargs, a.kw_defaults, strict=True) if d is not None]
            if any(sensitive_literal(arg.arg, default) for arg, default in pairs):
                return True
    return False


def _outside_names(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> set[str]:
    """Names the function reads that it does not define itself (and that are not builtins)."""
    bound: set[str] = {fn.name}
    for node in ast.walk(fn):
        if isinstance(node, (ast.Global, ast.Nonlocal)):
            bound.update(node.names)
            bound.add("<global>")  # makes the function refused below
        elif isinstance(node, ast.arg):
            bound.add(node.arg)
            node.annotation = None  # annotations are not evaluated in the generated file (postponed)
        elif isinstance(node, ast.Name) and isinstance(node.ctx, (ast.Store, ast.Del)):
            bound.add(node.id)
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            bound.add(node.name)
            if not isinstance(node, ast.ClassDef):
                node.returns = None
        elif isinstance(node, ast.ExceptHandler) and node.name:
            bound.add(node.name)
        elif isinstance(node, (ast.Import, ast.ImportFrom)):
            bound.update((alias.asname or alias.name).split(".")[0] for alias in node.names)
        elif isinstance(node, (ast.MatchAs, ast.MatchStar)) and node.name:
            bound.add(node.name)
        elif isinstance(node, ast.MatchMapping) and node.rest:
            bound.add(node.rest)
        elif isinstance(node, ast.AnnAssign):
            node.annotation = ast.Constant(value=None)
    free = {
        n.id
        for n in ast.walk(fn)
        if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Load) and n.id not in bound and not hasattr(builtins, n.id)
    }
    if "<global>" in bound:
        free.add("global/nonlocal")
    return free


def strip_connector_block(source: str) -> str:
    """Remove a previously generated connector block so regeneration is idempotent."""
    begin = source.find(BEGIN_MARKER)
    if begin == -1:
        return source
    end = source.find(END_MARKER, begin)
    tail = source[end + len(END_MARKER) :] if end != -1 else ""
    return source[:begin].rstrip() + "\n" + tail.lstrip("\n")


def render_tools_file(base_source: str, tools: Sequence[ConnectorTool]) -> str:
    """Base `tools.py` (parse_diff, get_file_context, lookup_rule) plus the connector tool wrappers."""
    base = strip_connector_block(base_source).rstrip() + "\n"
    if not tools:
        return base
    parts = [
        base,
        "",
        "",
        BEGIN_MARKER,
        "# Credentials are never stored here: these tools read them from environment variables that the",
        "# sandbox injects when the container starts.",
        "",
    ]
    for tool in tools:
        parts += ["", f"# connector: {tool.connector}", tool.source.rstrip(), ""]
    registry = ", ".join(f'"{t.name}": {t.name}' for t in tools)
    parts += ["", f"CONNECTOR_TOOLS = {{{registry}}}", END_MARKER, ""]
    return "\n".join(parts)
