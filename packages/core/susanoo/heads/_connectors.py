"""Connector lookup for Agent Smith. [PRD › Connectors and API budget › Connector contract]

Two kinds of connector can be selected:

1. **Registered connectors** (`susanoo.connectors.registry()`, Jugaad's `Connector` classes). Their
   `tools(credential)` returns `ConnectorTool`s whose `run` is a closure over the credential and the
   connector instance, and their `env(credential)` returns the environment variables the sandbox injects
   into the generated app's container. None of that is code that can be copied into the generated repo
   (which cannot import `susanoo`), so Agent Smith takes only what is independent of the real credential:
   the tool names, JSON schemas and read/write flags, and the env var NAMES (keys of `env()`, never
   values). It obtains them by calling `tools()` and `env()` with a clearly fake placeholder credential
   and discards every value. The real credential is never read here [CLAUDE.md §5].

   TODO(jugaad-connectors): the tool CODE of a registered connector is therefore not yet available to
   the generated agent. Needs a credential-free way to get it, for example `tool_sources()` or tools that
   read `os.environ[<VAR>]` with VAR from `env()`'s keys. Until then such a connector is recorded in
   `ConnectorInfo` with `tool_code_available=False` and the agent gets no tools from it.

2. **Legacy modules** `susanoo.connectors.<name>` with `spec` and `tools()` returning plain,
   self-contained functions. Their source is copied into the generated repo's `agent/tools.py` after AST
   vetting: each function must import what it needs inside its body and read its credential from an
   environment variable at call time. A function that hard-codes one is refused. Kept so the vetting
   path stays working and tested.

Agent Smith never reads a connection's stored configuration or credentials.
"""

from __future__ import annotations

import ast
import builtins
import importlib
import inspect
import json
import re
import textwrap
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from typing import Any, Protocol

from pydantic import SecretStr

from susanoo import connectors as real_connectors
from susanoo.integrations import tracing

BEGIN_MARKER = "# --- BEGIN CONNECTOR TOOLS (generated by Agent Smith; edit via the tool layer only) ---"
END_MARKER = "# --- END CONNECTOR TOOLS ---"


class ConnectorError(Exception):
    """A selected connector is missing or its tools cannot be used. The message is plain English."""


class ConnectorSpec(Protocol):
    name: str
    required_fields: Sequence[str]
    scopes: Sequence[str]
    read_actions: Sequence[str]
    write_actions: Sequence[str]


class ConnectorModule(Protocol):
    """Structural type of `susanoo.connectors.<name>` (a module works as well as an object)."""

    spec: ConnectorSpec

    def tools(self) -> Sequence[Callable[..., Any]]: ...


@dataclass(frozen=True)
class ConnectorTool:
    connector: str
    name: str
    source: str  # dedented Python source of one function, no credentials


@dataclass(frozen=True)
class ToolMeta:
    """What is known about a registered connector's tool without its credential."""

    name: str
    description: str  # plain English, from the connector's spec action (never from a credential-bound string)
    write: bool
    input_schema: dict[str, Any]


@dataclass(frozen=True)
class ConnectorInfo:
    """What Agent Smith learned about one selected connector. Names only: no values, no credentials."""

    id: str
    name: str
    env_vars: tuple[str, ...]  # keys of Connector.env(); the sandbox sets these, the agent reads them
    tools: tuple[ToolMeta, ...]
    tool_code_available: bool  # False until the connector contract can supply credential-free tool code


class RegisteredConnector:
    """Adapter over one of Jugaad's `Connector` classes, built with a placeholder credential only."""

    def __init__(self, connector: real_connectors.Connector) -> None:
        self.spec = connector.spec
        self.info = _describe_registered(connector)

    def tools(self) -> list[Any]:
        return []  # tool code is not extractable from a registered connector; see the module docstring


_CONNECTOR_NAME = re.compile(r"^[a-z][a-z0-9_]*$")
# An environment variable name such as GITHUB_TOKEN is how a tool is meant to find its credential.
_ENV_VAR_NAME = re.compile(r"^[A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+$")
_ENV_KEY = re.compile(r"^[A-Z][A-Z0-9_]{0,63}$")
# Obviously fake, and not shaped like any token, so nothing downstream mistakes it for a credential.
_PLACEHOLDER = "placeholder-not-a-credential"


def load_connectors(names: Sequence[str]) -> list[ConnectorModule]:
    """Return the connectors for `names`. This is the one place that knows where they live.

    A name in Jugaad's registry gives a `RegisteredConnector`; otherwise a `susanoo.connectors.<name>` module
    with `spec` and `tools()` is imported (the legacy path).
    """
    registered = _registry()
    connectors: list[ConnectorModule] = []
    for name in names:
        if not isinstance(name, str) or not _CONNECTOR_NAME.match(name):
            raise ConnectorError("A selected connection has an invalid name, so the agent was not given its tools.")
        if name in registered:
            connectors.append(RegisteredConnector(registered[name]))  # type: ignore[arg-type]
            continue
        try:
            module = importlib.import_module(f"susanoo.connectors.{name}")
        except ModuleNotFoundError as exc:
            raise ConnectorError(
                f"The {name} connection is not available yet, so the agent cannot be given its tools."
            ) from exc
        if not hasattr(module, "spec") or not callable(getattr(module, "tools", None)):
            raise ConnectorError(f"The {name} connection is not available yet, so the agent cannot be given its tools.")
        connectors.append(module)  # type: ignore[arg-type]
    return connectors


def _registry() -> dict[str, real_connectors.Connector]:
    try:
        return real_connectors.registry()
    except Exception as exc:
        raise ConnectorError("The list of available connections could not be loaded.") from exc


def _placeholder_credential(connector: real_connectors.Connector) -> real_connectors.Credential:
    settings = {f.name: _PLACEHOLDER for f in connector.spec.fields if not f.secret}
    return real_connectors.Credential(secret=SecretStr(_PLACEHOLDER), settings=settings, writes_enabled=False)


def _describe_registered(connector: real_connectors.Connector) -> ConnectorInfo:
    """Tool metadata and env var names via a placeholder credential. Every value returned is discarded."""
    spec = connector.spec
    cred = _placeholder_credential(connector)
    try:
        env_names = tuple(sorted(connector.env(cred)))
        real_tools = connector.tools(cred)
    except Exception as exc:  # the connector rejected the placeholder; never echo its message
        raise ConnectorError(
            f"The {spec.id} connection could not be described, so the agent was not given its tools."
        ) from exc
    bad = [k for k in env_names if not _ENV_KEY.match(k)]
    if bad:
        raise ConnectorError(f"The {spec.id} connection uses environment variable names that are not allowed.")
    described = {a.name: a.description for a in spec.actions}
    metas = tuple(
        ToolMeta(
            name=t.name,
            description=described.get(t.name, ""),
            write=bool(t.write),
            input_schema=dict(t.input_schema),
        )
        for t in real_tools
    )
    return ConnectorInfo(id=spec.id, name=spec.name, env_vars=env_names, tools=metas, tool_code_available=False)


def describe_connectors(connectors: Sequence[ConnectorModule], tools: Sequence[ConnectorTool]) -> list[ConnectorInfo]:
    """One `ConnectorInfo` per selected connector (legacy ones from their vetted `tools`)."""
    infos: list[ConnectorInfo] = []
    for connector in connectors:
        if isinstance(connector, RegisteredConnector):
            infos.append(connector.info)
            continue
        cname = str(connector.spec.name)
        metas = tuple(
            ToolMeta(name=t.name, description="", write=False, input_schema={}) for t in tools if t.connector == cname
        )
        infos.append(ConnectorInfo(id=cname, name=cname, env_vars=(), tools=metas, tool_code_available=True))
    return infos


def connector_env_names(names: Sequence[str]) -> dict[str, list[str]]:
    """For the Runner/sandbox: the env var NAMES each selected registered connector will set (keys only)."""
    return {c.info.id: list(c.info.env_vars) for c in load_connectors(names) if isinstance(c, RegisteredConnector)}


def collect_tools(connectors: Sequence[ConnectorModule]) -> list[ConnectorTool]:
    """Turn each connector's `tools()` into source snippets.

    A tool is refused (plain-English error naming the connector and tool, never any value) unless it is
    safe to copy into the generated repo: no credential in its source, no closure, and no reference to
    anything defined outside the function body (the generated repo cannot import susanoo).
    """
    tools: list[ConnectorTool] = []
    seen: set[str] = set()
    for connector in connectors:
        cname = str(connector.spec.name)
        for fn in connector.tools():
            fname = getattr(fn, "__name__", "")
            if not fname.isidentifier() or fname == "<lambda>":
                raise ConnectorError(f"A tool from the {cname} connection has no usable name, so it was not added.")
            if fname in seen:
                raise ConnectorError(f"Two connection tools are both called {fname!r}, so none were added.")
            seen.add(fname)
            source = _tool_source(cname, fname, fn)
            tools.append(ConnectorTool(connector=cname, name=fname, source=source))
    return tools


def _tool_source(cname: str, fname: str, fn: Any) -> str:
    def refuse(reason: str) -> ConnectorError:
        return ConnectorError(f"The {fname!r} tool from the {cname} connection was not added: {reason}")

    if not inspect.isfunction(fn):
        raise refuse("it is not a plain function.")
    if fn.__code__.co_freevars:
        raise refuse("it uses values from outside itself (a closure), which would not exist in the generated app.")
    try:
        source = textwrap.dedent(inspect.getsource(fn)).rstrip() + "\n"
        tree = ast.parse(source)
    except (OSError, TypeError, SyntaxError) as exc:
        raise refuse("its source is not plain, self-contained code.") from exc
    if len(tree.body) != 1 or not isinstance(tree.body[0], (ast.FunctionDef, ast.AsyncFunctionDef)):
        raise refuse("its source is not a single function.")
    node = tree.body[0]

    if tracing.looks_secret_shaped(source):
        raise refuse("it appears to contain a secret. Tools must read credentials from the environment.")
    if _hardcoded_credential(node):
        raise refuse("it appears to contain a hard-coded credential. Tools must read credentials from the environment.")
    outside = _outside_names(node)
    if outside:
        raise refuse(
            "it relies on names defined outside the function "
            f"({', '.join(sorted(outside)[:5])}). Import modules inside the function body."
        )
    return source


def _fold(node: ast.AST) -> str | None:
    """The string a literal expression evaluates to (joined literals, f-strings of only literals), else None."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        left, right = _fold(node.left), _fold(node.right)
        return left + right if left is not None and right is not None else None
    if isinstance(node, ast.JoinedStr):
        parts = [_fold(v) for v in node.values]
        return None if any(p is None for p in parts) else "".join(p for p in parts if p is not None)
    return None


def _is_credential_literal(value: str | None) -> bool:
    return bool(value) and not _ENV_VAR_NAME.match(value or "")


def _target_name(node: ast.AST) -> str | None:
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        return node.attr
    if isinstance(node, ast.Subscript):
        return _fold(node.slice)
    return None


def _hardcoded_credential(fn: ast.AST) -> bool:
    """True if a string literal is secret-shaped, or is bound to a credential-like name."""

    def sensitive_literal(name: str | None, value: ast.AST | None) -> bool:
        return (
            name is not None
            and value is not None
            and tracing.is_sensitive_name(name)
            and _is_credential_literal(_fold(value))
        )

    for node in ast.walk(fn):
        folded = _fold(node)
        if folded is not None and tracing.looks_secret_shaped(folded):
            return True
        if isinstance(node, ast.Assign):
            if any(sensitive_literal(_target_name(t), node.value) for t in node.targets):
                return True
        elif isinstance(node, (ast.AnnAssign, ast.AugAssign)):
            if sensitive_literal(_target_name(node.target), node.value):
                return True
        elif isinstance(node, ast.NamedExpr):
            if sensitive_literal(_target_name(node.target), node.value):
                return True
        elif isinstance(node, ast.keyword):
            if sensitive_literal(node.arg, node.value):
                return True
        elif isinstance(node, ast.Dict):
            for key, value in zip(node.keys, node.values, strict=True):
                if key is not None and sensitive_literal(_fold(key), value):
                    return True
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.Lambda)):
            a = node.args
            positional = [*a.posonlyargs, *a.args]
            pairs = list(zip(positional[len(positional) - len(a.defaults) :], a.defaults, strict=True))
            pairs += [(arg, d) for arg, d in zip(a.kwonlyargs, a.kw_defaults, strict=True) if d is not None]
            if any(sensitive_literal(arg.arg, default) for arg, default in pairs):
                return True
    return False


def _outside_names(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> set[str]:
    """Names the function reads that it does not define itself (and that are not builtins)."""
    bound: set[str] = {fn.name}
    for node in ast.walk(fn):
        if isinstance(node, (ast.Global, ast.Nonlocal)):
            bound.update(node.names)
            bound.add("<global>")  # makes the function refused below
        elif isinstance(node, ast.arg):
            bound.add(node.arg)
            node.annotation = None  # annotations are not evaluated in the generated file (postponed)
        elif isinstance(node, ast.Name) and isinstance(node.ctx, (ast.Store, ast.Del)):
            bound.add(node.id)
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            bound.add(node.name)
            if not isinstance(node, ast.ClassDef):
                node.returns = None
        elif isinstance(node, ast.ExceptHandler) and node.name:
            bound.add(node.name)
        elif isinstance(node, (ast.Import, ast.ImportFrom)):
            bound.update((alias.asname or alias.name).split(".")[0] for alias in node.names)
        elif isinstance(node, (ast.MatchAs, ast.MatchStar)) and node.name:
            bound.add(node.name)
        elif isinstance(node, ast.MatchMapping) and node.rest:
            bound.add(node.rest)
        elif isinstance(node, ast.AnnAssign):
            node.annotation = ast.Constant(value=None)
    free = {
        n.id
        for n in ast.walk(fn)
        if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Load) and n.id not in bound and not hasattr(builtins, n.id)
    }
    if "<global>" in bound:
        free.add("global/nonlocal")
    return free


def strip_connector_block(source: str) -> str:
    """Remove a previously generated connector block so regeneration is idempotent."""
    begin = source.find(BEGIN_MARKER)
    if begin == -1:
        return source
    end = source.find(END_MARKER, begin)
    tail = source[end + len(END_MARKER) :] if end != -1 else ""
    return source[:begin].rstrip() + "\n" + tail.lstrip("\n")


def render_tools_file(
    base_source: str, tools: Sequence[ConnectorTool], env_vars: Mapping[str, Sequence[str]] | None = None
) -> str:
    """Base `tools.py` (parse_diff, get_file_context, lookup_rule) plus the connector tool wrappers.

    `env_vars` maps connector id -> the env var names the sandbox sets for it; only names are written.
    """
    base = strip_connector_block(base_source).rstrip() + "\n"
    env_vars = {k: sorted(v) for k, v in (env_vars or {}).items() if v}
    if not tools and not env_vars:
        return base
    parts = [
        base,
        "",
        "",
        BEGIN_MARKER,
        "# Credentials are never stored here: these tools read them from environment variables that the",
        "# sandbox injects when the container starts.",
        "",
    ]
    if env_vars:
        parts += [
            "# Environment variable NAMES each connection sets (values are injected by the sandbox).",
            f"CONNECTOR_ENV_VARS = {json.dumps(env_vars, indent=4)}",
            "",
        ]
    for tool in tools:
        parts += ["", f"# connector: {tool.connector}", tool.source.rstrip(), ""]
    if tools:
        registry = ", ".join(f'"{t.name}": {t.name}' for t in tools)
        parts += ["", f"CONNECTOR_TOOLS = {{{registry}}}"]
    parts += [END_MARKER, ""]
    return "\n".join(parts)
