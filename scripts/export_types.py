"""Pydantic schemas and API models -> apps/web/types/generated.ts.

Fields with defaults (AnswerKey.must_not_flag, RunEvent.trace_url, ...) are always present in API
responses, so they are emitted as required, not optional.
"""

import importlib
import inspect
from pathlib import Path

from pydantic import BaseModel

OUT = Path(__file__).resolve().parent.parent / "apps/web/types/generated.ts"
# The frozen contracts, plus the platform API's own request/response models.
MODULES = [
    ("susanoo.schemas", ("susanoo.schemas", "susanoo")),
    ("susanoo_api.models", ("susanoo_api.models", "susanoo_api")),
]
# The AI-serving routers: the models each one defines (RunStatus, IntakeOut, ApprovalOut, FeedbackOut,
# ReportCards, ...) plus whatever its routes return (AgentCard). Imported helpers like CurrentUser stay out.
ROUTER_MODULES = [f"susanoo_api.routers.{name}" for name in ("runs", "intake", "approvals", "feedback", "agent")]
HEADER = "// Generated by scripts/export_types.py from Pydantic schemas. Do not edit by hand.\n"


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "enum" in schema:
        return " | ".join(repr_ts(v) for v in schema["enum"])
    if "const" in schema:
        return repr_ts(schema["const"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(ts_type(s) for s in schema[key])
    match schema.get("type"):
        case "string":
            return "string"
        case "integer" | "number":
            return "number"
        case "boolean":
            return "boolean"
        case "null":
            return "null"
        case "array":
            return f"Array<{ts_type(schema.get('items', {}))}>"
        case "object":
            extra = schema.get("additionalProperties")
            return f"Record<string, {ts_type(extra) if isinstance(extra, dict) else 'unknown'}>"
    return "unknown"


def repr_ts(value: object) -> str:
    return f'"{value}"' if isinstance(value, str) else str(value).lower()


def interface(name: str, schema: dict) -> str:
    if "enum" in schema:
        return f"export type {name} = {ts_type(schema)};\n"
    props = schema.get("properties", {})
    required = set(schema.get("required", [])) | {p for p, sub in props.items() if "default" in sub}
    lines = [f"  {prop}{'' if prop in required else '?'}: {ts_type(sub)};" for prop, sub in props.items()]
    return f"export interface {name} {{\n" + "\n".join(lines) + "\n}\n"


def main() -> None:
    models: list[type[BaseModel]] = []
    for name, roots in MODULES:
        try:
            module = importlib.import_module(name)
        except ModuleNotFoundError as exc:
            if exc.name not in roots:
                raise  # a broken import inside the module must fail loudly
            continue
        models += [
            m for _, m in inspect.getmembers(module, inspect.isclass) if issubclass(m, BaseModel) and m is not BaseModel
        ]
    for name in ROUTER_MODULES:
        module = importlib.import_module(name)
        models += [
            m
            for _, m in inspect.getmembers(module, inspect.isclass)
            if issubclass(m, BaseModel) and m.__module__ == name
        ]
        models += [
            route.response_model
            for route in module.router.routes
            if inspect.isclass(getattr(route, "response_model", None)) and issubclass(route.response_model, BaseModel)
        ]

    by_name: dict[str, type[BaseModel]] = {}
    for model in models:
        if by_name.setdefault(model.__name__, model) is not model:
            raise SystemExit(f"Two different models are both called {model.__name__}; rename one")

    defs: dict[str, dict] = {}
    for model in models:
        schema = model.model_json_schema(ref_template="#/$defs/{model}")
        defs.update(schema.pop("$defs", {}))
        defs[model.__name__] = schema

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(HEADER + "\n" + "\n".join(interface(n, s) for n, s in sorted(defs.items())))
    print(f"wrote {OUT.relative_to(OUT.parents[3])} ({len(defs)} types)")


if __name__ == "__main__":
    main()
